import { useState, type FormEvent } from "react";
import { useSearchParams } from "react-router-dom";
import { api, errorText } from "../api/client";
import type { AnswerEvaluation, Difficulty, Doc, Page, Quiz, QuizResult, QuizSummary } from "../api/types";
import { DocPicker } from "../components/DocPicker";
import { Badge, Button, Card, EmptyState, ErrorBanner, Field, Loading, PageHeader, Select, TextArea, TextInput } from "../components/ui";
import { useLoad, useStoredValue } from "../hooks";
import { fmtDate } from "../lib";

function QuizRunner({ quiz, onDone }: { quiz: Quiz; onDone: () => void }) {
  const [answers, setAnswers] = useState<(number | null)[]>(quiz.questions.map(() => null));
  const [result, setResult] = useState<QuizResult | null>(null);
  const [busy, setBusy] = useState(false); const [err, setErr] = useState<string | null>(null);
  const complete = answers.every((a) => a !== null);

  async function submit() {
    setBusy(true); setErr(null);
    try { setResult(await api.post<QuizResult>(`/quizzes/${quiz.id}/submit`, { answers })); onDone(); }
    catch (e) { setErr(errorText(e)); } finally { setBusy(false); }
  }
  return (
    <div>
      <h2>{quiz.topic}</h2>
      <p><Badge>{quiz.difficulty}</Badge> {quiz.grounded ? <Badge tone="mark">From your documents</Badge> : <Badge tone="warn">General knowledge</Badge>}</p>
      {result && <p role="status" className="score">{result.score} / {result.total} <small>({result.percent}%)</small></p>}
      <ErrorBanner message={err} />
      {quiz.questions.map((q, qi) => {
        const r = result?.results.find((x) => x.index === qi);
        return (
          <fieldset key={qi} className="quiz-q" disabled={!!result}>
            <legend>{qi + 1}. {q.prompt}</legend>
            {q.options.map((o, oi) => {
              const cls = r ? (oi === r.correct_index ? "right" : oi === r.given ? "wrong" : "") : "";
              return (
                <label key={oi} className={`quiz-opt ${cls}`}>
                  <input type="radio" name={`q${qi}`} checked={answers[qi] === oi}
                    onChange={() => setAnswers((a) => a.map((v, i) => (i === qi ? oi : v)))} />
                  <span>{o}{cls === "right" ? " (correct)" : cls === "wrong" ? " (your answer)" : ""}</span>
                </label>
              );
            })}
            {r && <p className="field-hint">{r.explanation}</p>}
          </fieldset>
        );
      })}
      {!result && <Button onClick={submit} loading={busy} disabled={!complete}>Submit answers</Button>}
      {!result && !complete && <p className="field-hint">Answer every question to submit.</p>}
    </div>
  );
}

function WrittenAnswer() {
  const [question, setQuestion] = useState(""); const [answer, setAnswer] = useState("");
  const [res, setRes] = useState<AnswerEvaluation | null>(null);
  const [busy, setBusy] = useState(false); const [err, setErr] = useState<string | null>(null);
  async function submit(e: FormEvent) {
    e.preventDefault(); setBusy(true); setErr(null); setRes(null);
    try { setRes(await api.post<AnswerEvaluation>("/assessments/evaluate", { question, answer })); }
    catch (x) { setErr(errorText(x)); } finally { setBusy(false); }
  }
  return (
    <Card title="Check a written answer">
      <form onSubmit={submit}>
        <ErrorBanner message={err} />
        <Field label="Question">{(id) => <TextInput id={id} required minLength={3} maxLength={1000} value={question} onChange={(e) => setQuestion(e.target.value)} />}</Field>
        <Field label="Your answer">{(id) => <TextArea id={id} rows={4} maxLength={3000} value={answer} onChange={(e) => setAnswer(e.target.value)} />}</Field>
        <Button type="submit" loading={busy} disabled={question.trim().length < 3}>Evaluate</Button>
      </form>
      {res && (
        <div role="status">
          <p><Badge tone={res.verdict === "correct" ? "ok" : res.verdict === "incorrect" ? "warn" : "neutral"}>{res.verdict.replace("_", " ")}</Badge> score {Math.round(res.score * 100)}%</p>
          <p>{res.feedback}</p>
          {res.missing_points.length > 0 && <ul>{res.missing_points.map((m, i) => <li key={i}>{m}</li>)}</ul>}
          <p className="field-hint">Evaluation is generated by an AI model and can be wrong.</p>
        </div>
      )}
    </Card>
  );
}

export function Quizzes() {
  const [params, setParams] = useSearchParams();
  const [lastOpen, setLastOpen] = useStoredValue("lumina.open.quiz");
  const openId = params.get("open") ?? lastOpen;  // coming back to this page reopens what you had open
  const openItem = (id: string) => { setLastOpen(id); setParams({ open: id }); };
  const list = useLoad(() => api.get<Page<QuizSummary>>("/quizzes", { limit: 30 }));
  const docs = useLoad(() => api.get<Page<Doc>>("/documents", { limit: 100 }));
  const current = useLoad(() => (openId ? api.get<Quiz>(`/quizzes/${openId}`) : Promise.resolve(null)), [openId]);
  const [topic, setTopic] = useState(""); const [difficulty, setDifficulty] = useState<Difficulty>("beginner");
  const [count, setCount] = useState(5); const [selected, setSelected] = useState<string[]>([]);
  const [busy, setBusy] = useState(false); const [err, setErr] = useState<string | null>(null);

  async function create(e: FormEvent) {
    e.preventDefault(); setBusy(true); setErr(null);
    try {
      const q = await api.post<Quiz>("/quizzes", { topic, difficulty, num_questions: count, ...(selected.length ? { document_ids: selected } : {}) });
      openItem(q.id); await list.reload();
    } catch (x) { setErr(errorText(x)); } finally { setBusy(false); }
  }
  return (
    <>
      <PageHeader title="Quizzes">Multiple-choice quizzes are scored on the server. The answer key is only revealed after you submit.</PageHeader>
      <div className="split">
        <div>
          <Card title="New quiz">
            <form onSubmit={create}>
              <ErrorBanner message={err} />
              <Field label="Topic">{(id) => <TextInput id={id} required minLength={2} maxLength={120} value={topic} onChange={(e) => setTopic(e.target.value)} />}</Field>
              <div className="row">
                <Field label="Difficulty">{(id) => (
                  <Select id={id} value={difficulty} onChange={(e) => setDifficulty(e.target.value as Difficulty)}>
                    <option value="beginner">Beginner</option><option value="intermediate">Intermediate</option><option value="advanced">Advanced</option>
                  </Select>)}</Field>
                <Field label="Questions">{(id) => <TextInput id={id} type="number" min={1} max={10} value={count} onChange={(e) => setCount(Math.max(1, Math.min(10, Number(e.target.value) || 1)))} />}</Field>
              </div>
              <DocPicker docs={docs.data?.items ?? []} selected={selected} onChange={setSelected} />
              <Button type="submit" loading={busy} disabled={topic.trim().length < 2}>Generate quiz</Button>
            </form>
          </Card>
          <Card title="Your quizzes">
            {list.loading && !list.data && <Loading label="Loading quizzes" />}
            <ErrorBanner message={list.error} onRetry={list.reload} />
            {list.data?.items.length === 0 && <EmptyState title="No quizzes yet">Generate one above.</EmptyState>}
            <ul className="plain">{list.data?.items.map((q) => (
              <li key={q.id}><button className="link" onClick={() => openItem(q.id)}>{q.topic}</button>
                <small className="muted"> {q.question_count} questions · {fmtDate(q.created_at)}{q.last_attempt ? ` · last ${q.last_attempt.percent}%` : ""}</small></li>))}</ul>
          </Card>
          <WrittenAnswer />
        </div>
        <Card>
          {busy && <Loading label="Generating your quiz" />}
          {!busy && openId && current.loading && <Loading label="Loading quiz" />}
          <ErrorBanner message={openId ? current.error : null} />
          {!busy && current.data && <QuizRunner key={current.data.id} quiz={current.data} onDone={() => void list.reload()} />}
          {!busy && !openId && <EmptyState title="No quiz open">Generate a quiz or pick one from your list.</EmptyState>}
        </Card>
      </div>
    </>
  );
}
